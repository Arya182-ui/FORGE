from abc import ABC, abstractmethod
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class AIExplanation(BaseModel):
    summary: str = Field(..., description="Technical summary of the finding")
    root_cause: str = Field(..., description="Root cause explanation")
    why_dangerous: str = Field(..., description="Why this vulnerability is dangerous")
    potential_impact: str = Field(..., description="Potential security impact")
    recommended_fix: str = Field(..., description="Recommended fix guidance")
    secure_example: str = Field(..., description="Secure code example")
    provider_name: str = Field("Rule-Based Engine", description="LLM provider name")
    model_name: str = Field("Built-in", description="LLM model name")
    is_ai_generated: bool = Field(False, description="True if generated by an active LLM")


class LLMProvider(ABC):
    @abstractmethod
    def is_available(self) -> bool:
        """Returns True if the LLM provider service is reachable."""
        pass

    @abstractmethod
    def generate_explanation(
        self,
        rule_id: str,
        title: str,
        severity: str,
        code_snippet: str,
        file_path: str,
        line_number: int,
        rule_description: str,
        owasp_category: str,
        built_in_explanation: Dict[str, str]
    ) -> AIExplanation:
        """Generates an AI-enriched explanation or fallback explanation."""
        pass
