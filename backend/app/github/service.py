import os
import tempfile
from pathlib import Path
from typing import Dict, Any, Optional, List

from backend.app.github.client import GitHubClient
from backend.app.scanner.engine import ScannerEngine
from backend.app.scanner.reporters.markdown_reporter import MarkdownReporter


COMMENT_MARKER = "<!-- FORGE-PR-SECURITY-REVIEW -->"


class GitHubPRScannerService:
    def __init__(self, github_client: Optional[GitHubClient] = None):
        self.github_client = github_client or GitHubClient()
        self.scanner_engine = ScannerEngine()

    def process_pr_scan(self, repo_full_name: str, pr_number: int, commit_sha: str) -> Dict[str, Any]:
        """
        Fetches modified PR files from GitHub, scans them with Forge Engine,
        and posts or updates the PR review summary comment.
        """
        pr_files = self.github_client.get_pr_files(repo_full_name, pr_number)
        if not pr_files:
            return {"status": "no_files", "message": "No modified files retrieved for PR."}

        # Create safe temporary directory for PR files
        with tempfile.TemporaryDirectory() as tmp_dir:
            tmp_path = Path(tmp_dir)

            for f_info in pr_files:
                filename = f_info.get("filename")
                raw_url = f_info.get("raw_url")
                status = f_info.get("status")

                if status == "removed" or not filename or not raw_url:
                    continue

                content = self.github_client.get_file_content(raw_url)
                if content is not None:
                    target_file_path = tmp_path / filename
                    target_file_path.parent.mkdir(parents=True, exist_ok=True)
                    target_file_path.write_text(content, encoding="utf-8", errors="replace")

            # Run Forge Security Scan on PR files
            report = self.scanner_engine.run_scan(str(tmp_path), save_to_db=True)

        summary = report.summary
        findings = report.findings

        # Format GitHub PR Comment Body
        comment_body = f"{COMMENT_MARKER}\n"
        comment_body += f"# 🛡️ FORGE — PR Security Analysis Review\n\n"
        comment_body += f"Automated security scan performed for PR **#{pr_number}** (`{commit_sha[:7] if commit_sha else 'head'}`).\n\n"
        comment_body += f"### Scan Summary\n"
        comment_body += f"- **Scanned Files**: {summary.scanned_files_count}\n"
        comment_body += f"- **Scanned Lines**: {summary.scanned_lines_count}\n"
        comment_body += f"- **Total Security Issues Found**: **{summary.total_findings_count}**\n"
        comment_body += f"- **Breakdown**: `CRITICAL: {summary.critical_count}` | `HIGH: {summary.high_count}` | `MEDIUM: {summary.medium_count}` | `LOW: {summary.low_count}`\n\n"

        if not findings:
            comment_body += "✅ **No security vulnerabilities found in PR files!**\n"
        else:
            comment_body += "### ⚠️ Findings Overview\n"
            comment_body += "| Severity | Rule | Location | Finding Title |\n"
            comment_body += "| --- | --- | --- | --- |\n"
            for f in findings:
                file_name = Path(f.file_path).name
                comment_body += f"| **{f.severity}** | `{f.rule_id}` | `{file_name}:{f.line_number}` | {f.title} |\n"

            comment_body += "\n---\n*Report generated by Forge AI-Assisted Security Platform.*"

        # Check existing PR comments for duplicate prevention
        existing_comments = self.github_client.list_pr_comments(repo_full_name, pr_number)
        existing_comment_id = None
        for c in existing_comments:
            if COMMENT_MARKER in c.get("body", ""):
                existing_comment_id = c.get("id")
                break

        if existing_comment_id:
            updated = self.github_client.update_pr_comment(repo_full_name, existing_comment_id, comment_body)
            action_taken = "updated_comment"
        else:
            posted = self.github_client.post_pr_comment(repo_full_name, pr_number, comment_body)
            action_taken = "posted_comment"

        return {
            "status": "success",
            "action": action_taken,
            "pr_number": pr_number,
            "findings_count": summary.total_findings_count,
            "critical_count": summary.critical_count,
            "high_count": summary.high_count,
            "comment_body": comment_body
        }
